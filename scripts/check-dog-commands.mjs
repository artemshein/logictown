import assert from 'node:assert/strict';
import {installDogCommands} from '../src/dog-commands.ts';
const action={textContent:''},close={},panel={hidden:false,setAttribute(){},querySelector:s=>s==='.dog-command-action'?action:close,remove(){}};
globalThis.window=new EventTarget();globalThis.document={createElement:()=>panel};
let interact=()=>{},lastCommand;
const dog={sitting:false,setInteraction(handler){interact=handler},command(next){lastCommand=next;this.sitting=next==='sit'}};
const menu=installDogCommands({append(){}},dog);
assert.equal(panel.hidden,true);interact();assert.equal(panel.hidden,false);assert.equal(action.textContent,'Сидеть');
action.onclick();assert.equal(lastCommand,'sit');assert.equal(action.textContent,'За мной');
action.onclick();assert.equal(lastCommand,'follow');assert.equal(action.textContent,'Сидеть');
dog.sitting=true;menu.update();assert.equal(action.textContent,'За мной','automatic sitting updates the visible action');
close.onclick();assert.equal(panel.hidden,true);interact();menu.update(false);assert.equal(panel.hidden,true);
menu.dispose();interact();assert.equal(panel.hidden,true,'disposed menu ignores dog clicks');
console.log('Dog command menu: click-to-open, state-dependent labels, both commands, automatic sitting and close/dispose verified.');
